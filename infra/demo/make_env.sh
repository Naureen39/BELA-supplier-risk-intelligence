#!/usr/bin/env bash
# Create .env with fresh random secrets for the compose stack. Never overwrites an existing file: rotating
# DATA_KEY makes encrypted values unreadable (docs/runbook.md), so an existing .env is left alone.
# Usage: infra/demo/make_env.sh [--demo]   (--demo adds the demo settings: Mailpit and the demo banner)
set -euo pipefail
cd "$(dirname "$0")/../.."
if [ -f .env ]; then echo ".env exists; leaving it unchanged"; exit 0; fi
command -v openssl >/dev/null || { echo "openssl is required to generate the signing key" >&2; exit 1; }
rand() { openssl rand -base64 33 | tr -d '/+=\n' | cut -c1-40; }
pem=$(openssl genpkey -algorithm ED25519 | awk 'NF {printf "%s\\n", $0}')
umask 077
{
  echo "# Generated by infra/demo/make_env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep it private; never commit it."
  echo "POSTGRES_PASSWORD=$(rand)"
  echo "DATA_KEY=$(rand)"
  echo "CURSOR_SECRET=$(rand)"
  echo "JWT_PRIVATE_KEY_PEM=\"$pem\""
  echo "SITE_ADDRESS=localhost"
  echo "ACME_EMAIL="
  if [ "${1:-}" = "--demo" ]; then
    echo "DEMO_MODE=true"
    echo "SMTP_HOST=mailpit"
    echo "SMTP_PORT=1025"
    echo "# To publish the read-only viewer password on the login page of a public demo, set it here, then rebuild:"
    echo "DEMO_VIEWER_PASSWORD="
  fi
} > .env
echo "wrote .env"
