"""List the licenses of the dependencies, from what is installed (Python) and from package-lock.json (npm).

    python infra/licenses.py [--out docs/licensing_dependencies.md]

Python licenses come from each installed package's metadata (the `License-Expression`, `License`, or a `License ::`
classifier), so run it in the environment the API uses. A package that declares nothing is listed as UNKNOWN: read
its repository rather than assuming. This is metadata, not legal advice.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def python_licenses() -> dict[str, str]:
    direct = {
        _norm(re.split(r"[=\[<>]", line)[0].strip())
        for line in (ROOT / "requirements/api.txt").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    }
    seen: dict[str, str] = {}
    todo = list(direct)
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            seen[name] = "NOT INSTALLED"
            continue
        m = dist.metadata
        lic = m.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split("::")[-1].strip() for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
            lic = "; ".join(classifiers) or (m.get("License") or "")
        lic = lic.strip().splitlines()[0][:60] if lic.strip() else "UNKNOWN"
        seen[name] = lic
        for req in dist.requires or []:
            if "extra ==" in req or "python_version" in req or "python_full_version" in req:  # extras and old-Python backports are not installed
                continue
            todo.append(_norm(re.split(r"[ ;<>=!~\[(]", req)[0]))
    return seen


def npm_licenses() -> dict[str, str]:
    lock = json.loads((ROOT / "apps/web/package-lock.json").read_text())
    out: dict[str, str] = {}
    for path, info in lock.get("packages", {}).items():
        if not path or info.get("dev"):
            continue
        out[path.split("node_modules/")[-1]] = str(info.get("license") or "UNKNOWN")
    return out


def table(title: str, found: dict[str, str]) -> list[str]:
    by = defaultdict(list)
    for pkg, lic in found.items():
        by[lic].append(pkg)
    counts = Counter({lic: len(p) for lic, p in by.items()})
    lines = [f"## {title}", "", f"{len(found)} packages.", "", "| License | Packages |", "|---|---|"]
    lines += [f"| {lic} | {n} |" for lic, n in counts.most_common()]
    odd = sorted(p for lic, ps in by.items() if lic in {"UNKNOWN", "NOT INSTALLED"} or re.search(r"GPL|AGPL|SSPL", lic) for p in ps)
    if odd:
        lines += ["", "Review these individually: " + ", ".join(odd)]
    return lines + [""]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=ROOT / "docs/licensing_dependencies.md")
    a = ap.parse_args()
    body = [
        "# Dependency licenses",
        "",
        "Generated by `python infra/licenses.py`. Python: the API runtime requirements (`requirements/api.txt`) and",
        "everything they install. npm: production dependencies of `apps/web` from `package-lock.json` (development",
        "tools are not shipped). The license is what each package declares in its metadata. See `docs/licensing.md`.",
        "",
    ]
    body += table("Python (API runtime)", python_licenses())
    body += table("npm (web, production)", npm_licenses())
    a.out.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
