import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { INDUSTRIES } from "@/content/industries";
import { LEGAL } from "@/content/legal";
import { SOLUTIONS } from "@/content/solutions";
import { PRICING } from "@/lib/site";

const root = join(__dirname, "..");
const ARTICLE_DIR = join(root, "src/content/articles");
const EM_DASH = String.fromCharCode(0x2014);

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory()
      ? ["node_modules", ".next", "reports", "test-results"].includes(e.name)
        ? []
        : walk(join(dir, e.name))
      : [join(dir, e.name)],
  );
}

describe("writing conventions", () => {
  const files = walk(root).filter(
    (f) => /\.(tsx?|mdx?|json|css|mjs)$/.test(f) && !f.endsWith("package-lock.json"),
  );
  it("never uses the em dash", () => {
    const bad = files.filter((f) => readFileSync(f, "utf8").includes(EM_DASH));
    expect(bad).toEqual([]);
  });
  it("never names an AI assistant or vendor tool", () => {
    const banned = /\b(chatgpt|openai|claude|anthropic|copilot|gemini|generated by)\b/i;
    const bad = files.filter((f) => !f.includes("tests/") && banned.test(readFileSync(f, "utf8")));
    expect(bad).toEqual([]);
  });
  it("avoids hype and fault wording in published copy", () => {
    const copy = walk(join(root, "src"))
      .filter((f) => /\.(tsx|ts|mdx)$/.test(f))
      .map((f) => readFileSync(f, "utf8"))
      .join("\n")
      .toLowerCase();
    for (const w of [
      "revolutionary",
      "world-class",
      "best-in-class",
      "game-changing",
      "cutting-edge",
      "guaranteed",
    ])
      expect(copy, w).not.toContain(w);
    expect(copy).not.toMatch(/\b(soc 2|iso 27001) (certified|compliant)\b/);
  });
});

describe("articles", () => {
  const files = readdirSync(ARTICLE_DIR).filter((f) => f.endsWith(".mdx"));
  it("has six articles of 900 to 1,400 words", () => {
    expect(files).toHaveLength(6);
    for (const f of files) {
      const body = readFileSync(join(ARTICLE_DIR, f), "utf8").replace(
        /export const meta[\s\S]*?};\n/,
        "",
      );
      const words = body.split(/\s+/).filter(Boolean).length;
      expect(words, f).toBeGreaterThanOrEqual(900);
      expect(words, f).toBeLessThanOrEqual(1400);
    }
  });
  it("exports metadata whose slug matches the file", () => {
    for (const f of files) {
      const src = readFileSync(join(ARTICLE_DIR, f), "utf8");
      expect(src).toContain(`slug: "${f.replace(".mdx", "")}"`);
      expect(src).toMatch(/date: "\d{4}-\d{2}-\d{2}"/);
    }
  });
});

describe("page content", () => {
  it("labels the illustrative pricing", () => {
    expect(PRICING.label).toBe("Illustrative pricing for the demo environment");
    expect(PRICING.plans.map((p) => p.name)).toEqual(["Starter", "Professional", "Enterprise"]);
  });
  it("matches the demo price list used by the revenue generator", () => {
    const gen = readFileSync(
      join(root, "../../data/scripts/generate_demo_business_data.py"),
      "utf8",
    );
    expect(gen).toContain('"starter": ("Starter", 499.0, 250, 40.0)');
    expect(gen).toContain('"professional": ("Professional", 1999.0, 2500, 120.0)');
    const byCode = Object.fromEntries(PRICING.plans.map((p) => [p.code, p]));
    expect([byCode.starter?.limit, byCode.professional?.limit]).toEqual([250, 2500]);
    expect([
      byCode.starter?.overage,
      byCode.professional?.overage,
      byCode.enterprise?.overage,
    ]).toEqual([40, 120, 300]);
  });
  it("has six industries, four solutions, and three legal documents", () => {
    expect(INDUSTRIES).toHaveLength(6);
    expect(SOLUTIONS).toHaveLength(4);
    expect(LEGAL.map((d) => d.slug)).toEqual(["privacy", "terms", "cookies"]);
  });
  it("labels every industry scenario as fictional", () => {
    for (const i of INDUSTRIES) expect(i.scenario.text.toLowerCase(), i.slug).toMatch(/fictional/);
  });
  it("never states fault as fact in industry or solution copy", () => {
    const all = JSON.stringify([INDUSTRIES, SOLUTIONS]).toLowerCase();
    expect(all).not.toMatch(/\b(violated|broke the law|was fined for|is guilty)\b/);
  });
});

describe("message catalogs", () => {
  const load = (l: string) =>
    JSON.parse(readFileSync(join(root, `messages/${l}.json`), "utf8")) as Record<
      string,
      Record<string, string>
    >;
  const keys = (o: Record<string, Record<string, string>>) =>
    Object.entries(o)
      .flatMap(([k, v]) => Object.keys(v).map((x) => `${k}.${x}`))
      .sort();
  it("has the same keys in every language", () => {
    const en = keys(load("en"));
    for (const l of ["es", "fr", "de"]) expect(keys(load(l)), l).toEqual(en);
  });
  it("keeps the disclaimer in every language", () => {
    for (const l of ["en", "es", "fr", "de"])
      expect(load(l).footer?.disclaimer?.length).toBeGreaterThan(30);
  });
});
